-- RentAll PostgreSQL bootstrap. Application data remains in a private non-API schema.
CREATE SCHEMA IF NOT EXISTS rentall;
REVOKE ALL ON SCHEMA rentall FROM PUBLIC, anon, authenticated;

CREATE TABLE rentall."AspNetRoles" (
 "Id" text PRIMARY KEY, "Name" varchar(256), "NormalizedName" varchar(256), "ConcurrencyStamp" text
);
CREATE TABLE rentall."AspNetUsers" (
 "Id" text PRIMARY KEY, "FirstName" varchar(255) NOT NULL, "LastName" varchar(255) NOT NULL,
 "UserName" varchar(256), "NormalizedUserName" varchar(256), "Email" varchar(256),
 "NormalizedEmail" varchar(256), "EmailConfirmed" boolean NOT NULL DEFAULT false,
 "PasswordHash" text, "SecurityStamp" text, "ConcurrencyStamp" text, "PhoneNumber" text,
 "PhoneNumberConfirmed" boolean NOT NULL DEFAULT false, "TwoFactorEnabled" boolean NOT NULL DEFAULT false,
 "LockoutEnd" timestamptz, "LockoutEnabled" boolean NOT NULL DEFAULT false, "AccessFailedCount" integer NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX "RoleNameIndex" ON rentall."AspNetRoles" ("NormalizedName");
CREATE UNIQUE INDEX "UserNameIndex" ON rentall."AspNetUsers" ("NormalizedUserName");
CREATE INDEX "EmailIndex" ON rentall."AspNetUsers" ("NormalizedEmail");

CREATE TABLE rentall."AspNetRoleClaims" (
 "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "RoleId" text NOT NULL REFERENCES rentall."AspNetRoles"("Id") ON DELETE CASCADE,
 "ClaimType" text, "ClaimValue" text
);
CREATE INDEX "IX_AspNetRoleClaims_RoleId" ON rentall."AspNetRoleClaims" ("RoleId");
CREATE TABLE rentall."AspNetUserClaims" (
 "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "UserId" text NOT NULL REFERENCES rentall."AspNetUsers"("Id") ON DELETE CASCADE,
 "ClaimType" text, "ClaimValue" text
);
CREATE INDEX "IX_AspNetUserClaims_UserId" ON rentall."AspNetUserClaims" ("UserId");
CREATE TABLE rentall."AspNetUserLogins" (
 "LoginProvider" varchar(128) NOT NULL, "ProviderKey" varchar(128) NOT NULL,
 "ProviderDisplayName" text, "UserId" text NOT NULL REFERENCES rentall."AspNetUsers"("Id") ON DELETE CASCADE,
 PRIMARY KEY ("LoginProvider", "ProviderKey")
);
CREATE INDEX "IX_AspNetUserLogins_UserId" ON rentall."AspNetUserLogins" ("UserId");
CREATE TABLE rentall."AspNetUserRoles" (
 "UserId" text NOT NULL REFERENCES rentall."AspNetUsers"("Id") ON DELETE CASCADE,
 "RoleId" text NOT NULL REFERENCES rentall."AspNetRoles"("Id") ON DELETE CASCADE,
 PRIMARY KEY ("UserId", "RoleId")
);
CREATE INDEX "IX_AspNetUserRoles_RoleId" ON rentall."AspNetUserRoles" ("RoleId");
CREATE TABLE rentall."AspNetUserTokens" (
 "UserId" text NOT NULL REFERENCES rentall."AspNetUsers"("Id") ON DELETE CASCADE,
 "LoginProvider" varchar(128) NOT NULL, "Name" varchar(128) NOT NULL,
 "Value" text, PRIMARY KEY ("UserId", "LoginProvider", "Name")
);
CREATE TABLE rentall."DataProtectionKeys" (
 "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "FriendlyName" text, "Xml" text
);
CREATE TABLE rentall."Categorias" (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nmcategoria text NOT NULL
);
CREATE TABLE rentall."Tipos" (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nmtipo text NOT NULL, categoriaid integer NOT NULL REFERENCES rentall."Categorias"(id) ON DELETE CASCADE
);
CREATE INDEX "IX_Tipos_categoriaid" ON rentall."Tipos" (categoriaid);
CREATE TABLE rentall."Items" (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nmitem text NOT NULL, dsitem text NOT NULL, dtcriacao timestamptz NOT NULL,
 snativo text NOT NULL, imagem1 text NOT NULL,
 imagem2 text, imagem3 text, imagem4 text, imagem5 text,
 iduser text NOT NULL REFERENCES rentall."AspNetUsers"("Id") ON DELETE CASCADE
);
CREATE INDEX "IX_Items_iduser" ON rentall."Items" (iduser);
CREATE TABLE rentall."Propostas" (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 multiplicador integer NOT NULL, vltotal real NOT NULL, "snAceitoProposta" text NOT NULL,
 idlocatario text NOT NULL, idlocador text NOT NULL
);
CREATE TABLE rentall."Anuncios" (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 vlitem real NOT NULL, "diasAluguel" integer NOT NULL,
 itemid integer NOT NULL REFERENCES rentall."Items"(id) ON DELETE CASCADE,
 categoriaid integer NOT NULL REFERENCES rentall."Categorias"(id),
 tipoid integer NOT NULL REFERENCES rentall."Tipos"(id),
 modelo text NOT NULL, iduser text NOT NULL,
 "CEP" varchar(9) NOT NULL, "Rua" text NOT NULL, "Numero" text,
 "Bairro" text NOT NULL, "Cidade" text NOT NULL, "Estado" text NOT NULL,
 "Complemento" text, contato text NOT NULL, "NomeFantasia" text NOT NULL
);
CREATE INDEX "IX_Anuncios_itemid" ON rentall."Anuncios" (itemid);
CREATE INDEX "IX_Anuncios_categoriaid" ON rentall."Anuncios" (categoriaid);
CREATE INDEX "IX_Anuncios_tipoid" ON rentall."Anuncios" (tipoid);
CREATE TABLE rentall."ImagensItems" (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 codimagem text NOT NULL, format text NOT NULL
);
CREATE TABLE rentall."Avaliacoes" (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 qtestrelas integer NOT NULL, dscomentario text NOT NULL,
 idavaliado text NOT NULL, idavaliador text NOT NULL,
 iditem integer NOT NULL REFERENCES rentall."Items"(id),
 idanuncio integer NOT NULL REFERENCES rentall."Anuncios"(id)
);
CREATE INDEX "IX_Avaliacoes_iditem" ON rentall."Avaliacoes" (iditem);
CREATE INDEX "IX_Avaliacoes_idanuncio" ON rentall."Avaliacoes" (idanuncio);
REVOKE ALL ON ALL TABLES IN SCHEMA rentall FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA rentall FROM PUBLIC, anon, authenticated;

